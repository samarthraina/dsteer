"""Generate under activation steering across a lambda grid.

One model, one direction, many lambdas. Positive lambda on the IT checkpoint pushes it
toward DPO behaviour; negative lambda on the DPO checkpoint pushes it back. Run the
script twice, once per side, to get both arms.

    python scripts/steer_sweep.py --model-config configs/tulu3.yaml \
        --eval-config configs/steer_sweep.yaml --side it

Writes one JSONL per lambda plus an unsteered baseline for that side. Resume is by
(lambda, prompt id): a lambda whose file already holds every prompt is skipped, and a
partial file is topped up. Scoring is a separate step -- this produces text only, so it
needs no judge server.

Note the baseline is generated by the same code path with the hooks inactive rather
than by a separate branch, so any difference between baseline and lambda=0 would be a
bug rather than a finding.
"""

