def pending(path: Path, records: List[Dict]) -> List[Dict]:
    """Records not already present in an output file."""
    if not path.exists():
        return records
    done = {r["id"] for r in read_jsonl(path)}
    return [r for r in records if r["id"] not in done]


def run_one(
    model, tokenizer, records, chats, coefficient, vectors, cfg, path, label, batch_size,
    mode: str = "add",
) -> int:
    """Generate for one lambda. Returns how many new records were written."""
    todo = pending(path, records)
    if not todo:
        return 0
    idx = {r["id"]: i for i, r in enumerate(records)}
    todo_chats = [chats[idx[r["id"]]] for r in todo]

    ctx = None
    if coefficient != 0.0 and vectors:
        def ctx():  # noqa: E306 -- rebuilt per batch so hooks never outlive it
            return ActivationSteering(
                model, vectors, coefficient=coefficient,
                positions=cfg.positions, preserve_norm=cfg.preserve_norm,
                mode=mode,
            )

    results = generate_batched(
        model, tokenizer, todo_chats,
        max_new_tokens=cfg.max_new_tokens,
        batch_size=batch_size,
        max_input_length=cfg.max_input_length,
        context=ctx,
        desc=label,
        return_metadata=True,
    )
    if len(results) != len(todo):
        # zip(...) would otherwise silently stop at the shorter sequence and drop the
        # remainder -- a count mismatch here means something upstream is already wrong,
        # and writing partial output would hide it.
        raise RuntimeError(
            f"generate_batched returned {len(results)} results for {len(todo)} pending "
            f"records ({label}); refusing to write a silently truncated batch"
        )

    for rec, result in zip(todo, results):
        out = dict(rec)
        if isinstance(out.get("prompt"), list):
            out["prompt_str"] = "\n".join(f"{m['role']}: {m['content']}" for m in out["prompt"])
        out["response"] = result.text
        out["generated_token_count"] = result.generated_token_count
        out["stop_reason"] = result.stop_reason
        out["stop_token_id"] = result.stop_token_id
        out["has_post_terminator_continuation"] = result.has_post_terminator_continuation
        out["lambda"] = coefficient
        append_jsonl(out, path)
    return len(todo)



def run_tag(side: str, args, extra: str = "") -> str:
    """Directory name for a run, distinguishing the vector it used.

    Generations resume by record id within their directory, so two runs that share a
    directory silently reuse each other's outputs. A learned vector and a mean-difference
    vector on the same checkpoint would otherwise collide, and the second would report the
    first's generations as its own -- which is exactly the comparison the frozen-vector
    experiment exists to make.
    """
    parts = [side, extra]
    # The vector's source is not otherwise in the path, so a run using a different
    # activations directory would land on an earlier run's generations and resume on
    # them -- reporting success while comparing a vector against itself.
    if getattr(args, "tag", None):
        parts.append("_" + args.tag)
    if getattr(args, "mode", "add") == "ablate":
        parts.append("_ablate")
    if getattr(args, "vectors", None):
        parts.append("_learned")
    if getattr(args, "layers", None):
        parts.append("_L" + args.layers.replace(",", "-"))
    if getattr(args, "hold_out", 0):
        parts.append(f"_ho{args.hold_out}")
    if getattr(args, "random_control", False):
        # The seed is part of the run's identity, not just its RNG state: five
        # controls with different seeds must land in five different directories, or
        # they collide, fail the metadata resume check, or silently reuse each
        # other's generations.
        parts.append(f"_random_s{getattr(args, 'random_seed', None)}")
    return "".join(parts)


def main():
    parser = argparse.ArgumentParser(description="Generate under activation steering across lambdas.")
    parser.add_argument(
        "--model-config", default=None,
        help="Legacy YAML model-pair config. Historical/non-confirmatory use only; "
             "mutually exclusive with endpoint-backed mode below.",
    )
    parser.add_argument(
        "--endpoint-manifest", default=None,
        help="Endpoint-backed mode: candidate endpoint manifest path (protocol Section 4).",
    )
    parser.add_argument(
        "--endpoint-bundle-root", default=None,
        help="Endpoint-backed mode: root directory holding merged endpoint bundles.",
    )
    parser.add_argument(
        "--pair", choices=["A", "B"], default=None,
        help="Endpoint-backed mode: which model pair to resolve from the candidate manifest.",
    )
    parser.add_argument(
        "--endpoint-source", action="append", default=[], metavar="ARTIFACT_ID=LOCAL_ROOT",
        help="Endpoint-backed mode: repeatable, local root for one direct source artifact "
             "(e.g. pair_a_sft=/data/pair_a/SFT_merged). Not needed for a merged endpoint, "
             "which resolves entirely under --endpoint-bundle-root.",
    )
    parser.add_argument("--eval-config", required=True)
    parser.add_argument(
        "--side", choices=["it", "dpo"], required=True,
        help="it: steer the IT checkpoint with +lambda. dpo: steer the DPO checkpoint with -lambda.",
    )
    parser.add_argument(
        "--random-control", action="store_true",
        help="Replace the vectors with norm-matched random directions. If this moves "
             "behaviour as much as the real ones, the sweep measures perturbation size. "
             "Requires --random-seed.",
    )
    parser.add_argument(
        "--random-seed", type=int, default=None, metavar="SEED",
        help="Required with --random-control: the random-direction identity, exactly "
             f"one of {RANDOM_CONTROL_SEEDS} (protocol Section 8). Independent of "
             "--seed, which is the general run seed and must never double as the "
             "random-direction identity -- five controls with the same --seed but "
             "different --random-seed must resolve to five different run directories.",
    )
    parser.add_argument(
        "--mode", choices=["add", "ablate"], default="add",
        help="How the vector is applied. 'add' puts lambda*v into the stream; 'ablate' "
             "projects the component along v out, which is what the refusal-direction "
             "line does and is not a rescaling of addition.",
    )
    parser.add_argument(
        "--tag", default=None,
        help="Appended to the run directory. Use it whenever the vector comes from a "
             "different activations source, so runs cannot resume on each other.",
    )
    parser.add_argument(
        "--vectors", default=None, metavar="VECTORS.PT",
        help="Use pre-built per-layer vectors instead of deriving them from activations, "
             "e.g. one trained by train_steering_vector.py. Overrides --layers.",
    )
    parser.add_argument(
        "--layers", default=None, metavar="L[,L...]",
        help="Steer exactly these layers, overriding layers_last_k. One layer at a time "
             "is how 'why only the final layers' gets an answer rather than an assertion; "
             "a shared scalar over five of them is not equal intervention, since the "
             "displacement grows with depth.",
    )
    parser.add_argument(
        "--hold-out", type=int, default=0,
        help="Drop this many leading samples when building the vector. Use the "
             "sweep's prompt count when the vector and the evaluation come from "
             "the same corpus, so the two sets are disjoint. Must be 0 for every "
             "manifest-backed prompt_source (harmfulqa, hh_rlhf, advbench): their "
             "construction and evaluation partitions are already disjoint by manifest.",
    )
    parser.add_argument(
        "--partition", choices=sorted(VALID_HARMFULQA_PARTITIONS), default=None,
        help="HarmfulQA partition, overriding prompt_partition in the eval config. "
             "Only 'development' or 'calibration' are accepted for this grid-search "
             "script when prompt_source='harmfulqa'; rejected outright (never silently "
             "ignored) when prompt_source is 'hh_rlhf' or 'advbench'.",
    )
    parser.add_argument("--seed", type=int, default=42)
    parser.add_argument("--sync", action="store_true")
    parser.add_argument("--hourly-rate", type=float, default=None)
    args = parser.parse_args()

    # A pure CLI-shape check (--random-control and --random-seed must travel
    # together) -- before endpoint verification even runs, since it needs nothing from
    # it and has no side effects of its own.
    validate_random_seed_args(args)

    # Endpoint verification (frozen-source binding, candidate-manifest hash/structural
    # validation, and per-file SHA-256/size streaming, for endpoint-backed mode)
    # happens here, before anything below -- including `set_all_seeds`, which touches
    # CUDA (`torch.cuda.is_available()`/`manual_seed_all`) on a GPU machine -- creates
    # output, initializes logging, or loads a prompt, vector, model, or GPU resource. A
    # mismatch has no side effects.
    model_cfg, endpoint_meta = resolve_model_source(
        model_config=args.model_config, endpoint_manifest=args.endpoint_manifest,
        endpoint_bundle_root=args.endpoint_bundle_root, pair=args.pair, endpoint_source=args.endpoint_source,
    )
    endpoint_backed = endpoint_meta is not None

    cfg = SteerSweepConfig.from_yaml(args.eval_config)

    partition = resolve_prompt_partition(cfg, args.partition)
    reject_hold_out_for_manifest_backed_source(cfg.prompt_source, args.hold_out)

    # The effective layer set, and the protocol-profile classification it feeds into,
    # are both resolved from config/CLI facts only -- before set_all_seeds (CUDA),
    # prompt loading, output creation, metadata writing, logging, checkpoint deletion,
    # model/tokenizer loading, vector loading, or generation. A profile mismatch
    # raises here, before any of that has run.
    layers = resolve_effective_layers(args, cfg, model_cfg)
    protocol_profile = classify_protocol_profile(RunProfileInputs(
        endpoint_backed=endpoint_backed,
        lambdas=tuple(cfg.lambdas), layers=tuple(layers),
        vector_method=cfg.vector_method, vector_normalise=cfg.vector_normalise,
        positions=cfg.positions, preserve_norm=cfg.preserve_norm,
        max_new_tokens=cfg.max_new_tokens, max_input_length=cfg.max_input_length,
        mode=args.mode, random_control=args.random_control, random_seed=args.random_seed,
        external_vectors=bool(args.vectors),
        single_layer_override=bool(args.layers) and len(layers) == 1,
    ))
    loading_policy = _model_loading_policy(endpoint_backed)

    # For an endpoint-backed, non-external-vectors run, the construction-activation
    # sidecar (Task 016) is required and validated against the endpoint pair resolved
    # for *this* run here -- still before set_all_seeds (CUDA), output creation,
    # metadata writing, logging, or any tokenizer/model/GPU access. (An endpoint-backed
    # run with --vectors already raised inside classify_protocol_profile above, so
    # endpoint_backed here implies not args.vectors; the check is kept explicit for
    # clarity.) Vectors are only ever built, below, from this already-validated artifact.
    activation_artifact_result = None
    if endpoint_backed and not args.vectors:
        activation_artifact_result = validate_activation_artifact_for_run(cfg, model_cfg, endpoint_meta)

    tag = run_tag(args.side, args)
    out_root = Path(cfg.output_dir) / model_cfg.name / output_source_segment(cfg.prompt_source, partition) / tag

    # Dataset binding: load prompts (and, for the manifest-backed sources, validate
    # their panel provenance) before set_all_seeds (CUDA), output/metadata mutation,
    # logging setup, or any tokenizer/model/vector loading (Task 019). Both steps here
    # are read-only -- they mutate nothing on disk -- so a malformed panel, a drifted
    # frozen-panel record count, or ambiguous/missing provenance fails here, before any
    # side effect has run.
    records = load_prompts(cfg.prompt_source, cfg.n_prompts, args.seed, partition)
    panel_meta = build_prompt_panel_metadata(cfg.prompt_source, records)

    run_meta_extra: Dict[str, Any] = {}
    if cfg.prompt_source == "harmfulqa":
        # Preserved for compatibility alongside the generic prompt_panel block below.
        run_meta_extra["harmfulqa_partition"] = partition
        run_meta_extra["harmfulqa_manifest_hash"] = panel_meta["manifest_hash"]
        run_meta_extra["harmfulqa_record_count"] = panel_meta["record_count"]
    run_meta_extra["prompt_panel"] = panel_meta
    run_meta_extra["protocol_profile"] = protocol_profile
    run_meta_extra["endpoint_backed"] = endpoint_backed
    run_meta_extra["model_loading_policy"] = loading_policy
    run_meta_extra["resolved_layers"] = layers
    run_meta_extra["random_control_seed"] = args.random_seed if args.random_control else None
    if endpoint_meta is not None:
        run_meta_extra["endpoint"] = endpoint_meta
    if activation_artifact_result is not None:
        run_meta_extra["activation_artifact"] = {
            "path": str(activation_artifact_result.acts_path),
            "sha256": activation_artifact_result.sha256,
            "size_bytes": activation_artifact_result.size_bytes,
            "run_identity_hash": activation_artifact_result.sidecar.get("run_identity_hash"),
            "endpoint": activation_artifact_result.sidecar.get("endpoint"),
        }

    # The metadata resume/mismatch check -- still before set_all_seeds (CUDA), logging,
    # model loading, or generation: a mismatched resume fails here, before it can touch
    # any of that.
    write_run_metadata(
        out_root,
        config=build_run_config(model_cfg, cfg, args),
        extra=run_meta_extra,
        argv=list(sys.argv),
    )

    set_all_seeds(args.seed)

    # Nothing above initialised the log or loaded any model/tokenizer/vectors -- a
    # mismatched resume, a malformed prompt panel, or a protocol-profile mismatch all
    # fail before this point, with no side effects.
    log = setup_logging(out_root / "steer_sweep.log")
    log.info(f"{len(records)} prompts from {cfg.prompt_source}" + (f" partition={partition}" if cfg.prompt_source == "harmfulqa" else ""))
    log.info(f"protocol_profile={protocol_profile}")

    # Vectors come from the activations for this pair, at the response readout.
    if args.vectors:
        # A vector trained under the DPO loss, rather than read off a checkpoint pair.
        # It arrives already per-layer, so the layer set comes from the file --
        # overriding the placeholder `layers` resolved above for classification
        # (protocol_profile is never primary_v1 for an external-vectors run; see
        # classify_protocol_profile).
        loaded = torch.load(Path(args.vectors), map_location="cpu")
        vectors = {int(k): v.float() for k, v in loaded.items()}
        layers = sorted(vectors)
        log.info(f"Loaded {len(vectors)} vectors from {args.vectors}; layers {layers}")
    elif activation_artifact_result is not None:
        # Already required and validated (sidecar-bound, endpoint-matched) above,
        # before set_all_seeds -- build directly from that same verified file.
        acts = activation_artifact_result.acts_path
        vectors = build_vectors(acts, method=cfg.vector_method, layers=layers,
                                normalise=cfg.vector_normalise,
                                skip_first=args.hold_out)
    else:
        # Legacy (non-endpoint-backed): unchanged behavior -- no sidecar is involved.
        acts = Path(cfg.activations_dir) / model_cfg.name / "construction" / "activations.pt"
        if not acts.exists():
            raise FileNotFoundError(f"no activations at {acts}; run layer_profile first")
        validate_construction_activations(torch.load(acts, map_location="cpu"))
        vectors = build_vectors(acts, method=cfg.vector_method, layers=layers,
                                normalise=cfg.vector_normalise,
                                skip_first=args.hold_out)
    if args.random_control:
        vectors = random_vectors_like(vectors, seed=args.random_seed)
        log.info(f"Using norm-matched RANDOM directions (control), random_seed={args.random_seed}")
    log.info(f"Steering layers {layers[0]}-{layers[-1]} with method={cfg.vector_method}")

    which = model_cfg.it_model if args.side == "it" else model_cfg.dpo_model
    sub = (model_cfg.it_subfolder if args.side == "it" else model_cfg.dpo_subfolder) or ""
    tokenizer = load_tokenizer(model_cfg.tokenizer_id or which,
                               subfolder=model_cfg.tokenizer_subfolder or sub,
                               **loading_policy)
    model = load_model(which, subfolder=sub, **loading_policy)
    chats = build_chat_prompts(tokenizer, [r["prompt"] for r in records])

    batch_size = cfg.batch_size or suggest_batch_size(model)
    log.info(f"batch size {batch_size}")

    # Ablation has no direction to reverse: removing a component is the same operation
    # whichever checkpoint it is done on, and a negative coefficient would *add* the
    # component back rather than take more of it out. Only addition takes the sign.
    sign = 1.0 if (args.side == "it" or args.mode == "ablate") else -1.0
    grid = [0.0] + [sign * abs(l) for l in cfg.lambdas]

    written = 0
    with GpuMonitor(out_root, hourly_rate=args.hourly_rate) as gpu:
        for coeff in grid:
            name = "baseline" if coeff == 0.0 else f"lambda_{coeff:+.3f}"
            path = out_root / f"{name}.jsonl"
            n = run_one(model, tokenizer, records, chats, coeff, vectors, cfg,
                        path, f"{model_cfg.name} {tag} {name}", batch_size,
                        mode=args.mode)
            written += n
            log.info(f"{name}: +{n} records -> {path}")

    log.info(f"GPU usage: {json.dumps(gpu.summary())}")
    log.info(f"{written} new generations across {len(grid)} settings")

    del model
    gc.collect()
    torch.cuda.empty_cache()

    if args.sync:
        sync_to_hub(out_root, experiment=f"steer_{cfg.prompt_source}",
                    model=f"{model_cfg.name}_{tag}")


if __name__ == "__main__":
    main()
